#!/bin/sh
# نقطة الدخول — تُشغَّل في الحاويات الثلاث (الويب · الطابور · المجدول).
#
# ولا تُهاجر القاعدة هنا: ثلاث حاويات تُقلع معًا تعني ثلاث هجراتٍ متزامنة على
# القاعدة نفسها. الهجرة خطوةٌ صريحة في `scripts/deploy.sh` تسبق الإقلاع.
set -e

# ─── مفتاح التطبيق: يُرفض غيابه ولا يُولَّد ───
#
# `key:generate` عند كل إقلاع تبدو حلًّا وهي **إتلافٌ صامت**: أسرار الجسر
# وتوقيعات التنبيهات مشفَّرة بالمفتاح، فمفتاحٌ جديد يجعلها كلها غير قابلة
# للفكّ — بلا خطأ واحد، إلى أن يُخفق أول نداء ولا يُعرف السبب.
if [ -z "${APP_KEY}" ]; then
    echo "APP_KEY غير مضبوط. ولّده مرة واحدة بـ 'php artisan key:generate --show' وضعه في .env." >&2
    echo "لا يُولَّد هنا: مفتاح جديد يُبطل كل سرٍّ مشفَّر محفوظ (أسرار الجسر وتوقيعات التنبيهات)." >&2
    exit 1
fi

if [ "${APP_DEBUG}" = "true" ]; then
    echo "APP_DEBUG=true في الإنتاج: صفحة الخطأ تكشف الإعداد والمسارات وقيم البيئة لكل زائر." >&2
    exit 1
fi

# ─── انتظار القاعدة ───
#
# الحاوية التي تُقلع قبل قاعدتها تسقط، فيعيدها Docker، فتبدو «تعيد التشغيل
# باستمرار» — وهو عَرَضٌ يُبحث عنه في التطبيق والسبب في الترتيب.
if [ -n "${DB_HOST}" ]; then
    tries=0
    until pg_isready -h "${DB_HOST}" -p "${DB_PORT:-5432}" -U "${DB_USERNAME}" -q; do
        tries=$((tries + 1))
        if [ "${tries}" -ge 30 ]; then
            echo "القاعدة ${DB_HOST}:${DB_PORT:-5432} لم تستجب بعد ٦٠ ثانية." >&2
            exit 1
        fi
        sleep 2
    done
fi

# ─── الذاكرة المؤقتة تُبنى هنا لا في الصورة ───
#
# `config:cache` وقت البناء يخبز قيم البيئة داخل الصورة، فتحمل الصورة أسرار
# البيئة التي بُنيت فيها وتتجاهل ما يُمرَّر إليها بعدها.
php artisan config:cache
php artisan route:cache
php artisan view:cache

if [ ! -L public/storage ]; then
    php artisan storage:link || true
fi

chown -R www-data:www-data storage bootstrap/cache

exec "$@"
