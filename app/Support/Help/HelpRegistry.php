    public function all(): array
    {
        $topics = [];

        foreach ($this->topics() as $topic) {
            $topics[$topic->screen] = $topic;
        }

        return $topics;
    }

    public function find(string $screen): ?HelpTopic
    {
        return $this->all()[$screen] ?? null;
    }

